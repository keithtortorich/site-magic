"""Demo site fixtures for the 9 SUPPORTED_INDUSTRIES trades.

Per ADR-030 (docs/ADR-030_DEMO_SITES_VIA_SITEMAGIC.md): demo sites are
generated by the same Site Magic pipeline a paying tenant's site runs
through, not hand-authored static HTML. This module supplies only the
*input* -- the verified_facts payload a Site Magic "intake" source job
needs -- keyed by a stable public slug and a reserved, system-only
tenant_id that can never collide with a real customer (see
RESERVED_TENANT_PREFIX and its enforcement in intake.py).

Content rules (carried forward from the prior static-demo cleanup,
docs/STANDUP_2026-08-09_AGENCY_ROOT_AND_DEMOS.md), still binding because
site_data.py's no-fabrication invariant and NETBUILD_GOVERNANCE.md's
em-dash ban apply to every surface, demos included:

- No rating_value, review_count, or testimonials -- a demo business has
  no customers, so it gets no review data and no AggregateRating markup.
- No certifications -- those are credentials, not illustrative copy.
- Phone numbers from the 555-0100 to 555-0199 block reserved for
  fictional use (see ATIS/NANPA), so a prospect tapping "call" on a demo
  can never reach a real stranger.
- Emails on the reserved example.com domain (RFC 2606).
- No em-dashes anywhere in the copy.

Business names/taglines/differentiators/services are drawn from
trade_presets.py's TRADE_HINTS, which is already illustrative-only
placeholder copy (see that module's own docstring) -- reusing it here
means demo copy and intake-form placeholder copy stay in sync instead of
being a second, separately-maintained set of fictional businesses.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from .trade_presets import TRADE_HINTS

RESERVED_TENANT_PREFIX = "_demo_"

# Slug -> canonical industry key in trade_presets.TRADE_HINTS. Order here
# is display order for the /demos gallery. "Other" is deliberately
# excluded -- it's a fallback preset, not a real trade to showcase.
DEMO_SLUGS: dict[str, str] = {
    "hvac": "HVAC",
    "plumbing": "Plumber",
    "electrical": "Electrician",
    "roofing": "Roofing",
    "water-restoration": "Water Damage Restoration",
    "garage-door": "Garage Door Repair",
    "pest-control": "Pest Control",
    "landscaping": "Landscaping",
    "tree-service": "Tree Service",
    "cleaning": "Cleaning Services",
}

# Reserved 555 block, one distinct extension per demo so a prospect
# calling from two different demo pages never dials the same fictional
# number. Order matches DEMO_SLUGS.
_DEMO_PHONE_EXTENSIONS = {
    "hvac": "0101",
    "plumbing": "0102",
    "electrical": "0103",
    "roofing": "0104",
    "water-restoration": "0105",
    "garage-door": "0106",
    "pest-control": "0107",
    "landscaping": "0108",
    "tree-service": "0109",
    "cleaning": "0110",
}


@dataclass(frozen=True)
class DemoFixture:
    slug: str
    reserved_tenant_id: str
    industry_key: str
    verified_facts: dict[str, Any] = field(default_factory=dict)


def _build_verified_facts(slug: str, industry_key: str) -> dict[str, Any]:
    hint = TRADE_HINTS[industry_key]
    ext = _DEMO_PHONE_EXTENSIONS[slug]
    return {
        "tenant_id": f"{RESERVED_TENANT_PREFIX}{slug.replace('-', '_')}",
        "biz_name": hint["biz"],
        "phone": f"(555) {ext}",
        "email": f"contact@{slug.replace('-', '')}.example.com",
        "industry": industry_key,
        "service_area": "Phoenix Metro, AZ",
        "tagline": hint["tagline"],
        "differentiator": hint["differentiator"],
        "services": list(hint["services"]),
        "plan": "office_staff",
        # Deliberately omitted (no-fabrication invariant, STANDUP rules):
        # rating_value, review_count, testimonials, certifications,
        # license_number (a credential, same reasoning as certifications).
    }


DEMO_FIXTURES: dict[str, DemoFixture] = {
    slug: DemoFixture(
        slug=slug,
        reserved_tenant_id=f"{RESERVED_TENANT_PREFIX}{slug.replace('-', '_')}",
        industry_key=industry_key,
        verified_facts=_build_verified_facts(slug, industry_key),
    )
    for slug, industry_key in DEMO_SLUGS.items()
}

# Legacy slugs/filenames (retired static demos, both the 2026-08-09
# /demos/{slug} attempt and the older /demo-sites/{file}.html era still
# linked from the landing page's own copy) -> current canonical slug, so
# a link already handed to a prospect 301s instead of 404ing.
LEGACY_SLUG_REDIRECTS: dict[str, str] = {
    "arbor": "tree-service",
    "waterrestore": "water-restoration",
    "roof": "roofing",
    "landscape": "landscaping",
    "pest": "pest-control",
    "garage": "garage-door",
    "maid": "cleaning",
    "electric": "electrical",
}


def get_fixture(slug: str) -> DemoFixture | None:
    return DEMO_FIXTURES.get(slug)


def is_reserved_tenant_id(tenant_id: str) -> bool:
    """True for any tenant_id in the demo-reserved namespace, whether or
    not it matches a currently-defined fixture -- the prefix itself is
    reserved, not just the specific slugs built today, so a future demo
    addition never needs a second enforcement point."""
    return tenant_id.startswith(RESERVED_TENANT_PREFIX)
